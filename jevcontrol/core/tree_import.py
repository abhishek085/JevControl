    """Fidelity: of this trace's agreed decisions, how many match what the export originally recorded."""
    graded = [(s["key"], s["logged"]) for s in task["steps"] if s.get("logged")]
    if not graded:
        return 1.0
    hit = sum(1 for key, logged in graded if str(out.get(key, "")).strip().lower() == str(logged).strip().lower())
    return hit / len(graded)
